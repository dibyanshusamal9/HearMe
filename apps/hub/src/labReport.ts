import { languageName } from '@hearme/shared';
import { LAB_MICS, LAB_MODES, LAB_OUTCOMES, LAB_PLACES, OUTCOME_LABEL, fmtRate, fmtSeconds, labItemLabel, pct, summarizeBy, summarizeTakes, type LabSummary, type LabTake } from '@hearme/shared/lab';

/**
 * Markdown for docs/voice-lab.md, from the voice lab's takes (`npm run lab-report`).
 * `names`: language packs' own names ("Bengali", where Intl may say "Bangla").
 */
export function renderLabReport(takes: LabTake[], generatedAt = new Date(), names: Record<string, string> = {}): string {
  const langLabel = (t: LabTake) => `${names[t.lang] ?? languageName(t.lang)}${t.speaker === 'crew' ? ' (crew)' : ''}`;
  const passenger = takes.filter((t) => t.speaker === 'passenger');
  const crew = takes.filter((t) => t.speaker === 'crew');
  const people = new Set(takes.map((t) => t.tester || '(no name)'));
  const sittings = new Set(takes.map((t) => t.session));
  const days = takes.map((t) => t.at.slice(0, 10)).sort();
  const models = [...new Set(takes.map((t) => t.model.split('/').pop()))].join(', ');
  const langs = summarizeBy(takes, langLabel)
    .map((r) => `${r.label} ${r.takes}`)
    .join(', ');

  const out: string[] = [];
  out.push('# Voice lab: HearMe with real voices', '');
  out.push(`_Generated by \`npm run lab-report\` on ${generatedAt.toISOString().slice(0, 10)} from ${takes.length} takes in apps/hub/.lab/takes.jsonl. Do not edit by hand: record more takes and run it again._`, '');
  out.push(
    `**Who:** ${people.size} ${people.size === 1 ? 'person' : 'people'} (${[...people].join(', ')}), ${sittings.size} ${sittings.size === 1 ? 'sitting' : 'sittings'}, ${days[0]}${days.at(-1) !== days[0] ? ` to ${days.at(-1)}` : ''}. Takes by language: ${langs}.`,
    '',
    '**How:** each person held a button on the voice lab page (`#/lab`) and said what was asked: a sentence from the held-out set that never tuned the matcher, or a request in their own words from a picture. The hub ran exactly what a passenger’s phone runs (16 kHz audio → Whisper on the hub laptop → keyword + multilingual-e5 matching) and scored what would have appeared on screen.',
    '',
    `**Speech model:** ${models}. **Times** are on the hub laptop, from the recording arriving to the answer; Wi-Fi upload comes on top.`,
    '',
  );

  out.push('## Headline', '');
  const heads = [...(passenger.length ? [summarizeTakes(passenger, 'Passenger requests')] : []), ...(crew.length ? [summarizeTakes(crew, 'Crew replies (Japanese)')] : [])];
  out.push(table(heads, ''), '');
  if (passenger.length) {
    const p = summarizeTakes(passenger);
    const heard = p.takes - p.counts.silent;
    out.push(
      `- The right picture appeared, ready to send, in **${pct(p.counts.right, p.takes)}** of ${p.takes} passenger requests; counting one extra tap on “Did you mean…?”, **${pct(p.counts.right + p.counts.offered, p.takes)}**.`,
      `- A **wrong** picture appeared first in **${p.counts.wrong}** (${pct(p.counts.wrong, p.takes)}). The passenger sees the picture before sending, so they can still catch it, but this is the number to keep low.`,
      `- Whisper heard nothing in ${p.counts.silent} take${p.counts.silent === 1 ? '' : 's'}; of the ${heard} it heard, the median time on the hub was **${fmtSeconds(p.medianMs)}** (90% within ${fmtSeconds(p.p90Ms)}, 95% within ${fmtSeconds(p.p95Ms)}).`,
      `- The passenger had to fall back to tapping or typing in **${Math.round(p.fallbackRate * 100)}%** of takes (asked without the right picture, or nothing heard).`,
      ...(p.wer
        ? [
            `- Speech-to-text ${p.wer.unit} error rate was **${fmtRate(p.wer)}** over the ${p.werTakes} takes that read a given sentence (${p.wer.edits} ${p.wer.unit}s wrong out of ${p.wer.reference}). This is how wrong the *text* was, before any matching: a high error rate with a low "wrong one shown" means the matcher is recovering from bad transcripts, which is what it is built to do.`,
          ]
        : ['- Speech-to-text error rate: not measurable here, because no take read a given sentence (own-words takes have no reference text to compare against).']),
      '',
    );
  }
  if (crew.length) {
    const c = summarizeTakes(crew);
    out.push(`- Crew speaking Japanese: the right verified reply was suggested in **${pct(c.counts.right, c.takes)}** of ${c.takes}; a wrong one in ${pct(c.counts.wrong, c.takes)} (crew confirm every suggestion before it is sent).`, '');
  }

  if (passenger.length) {
    out.push('## Passengers, by language', '', table(summarizeBy(passenger, langLabel), 'Language'), '');
  }
  for (const [title, key] of [
    ['Passengers, by place', (t: LabTake) => LAB_PLACES[t.place]],
    ['Passengers, by microphone', (t: LabTake) => LAB_MICS[t.mic]],
    ['Passengers: reading a sentence vs own words', (t: LabTake) => LAB_MODES[t.mode]],
    ['Passengers: first language or not', (t: LabTake) => (t.firstLanguage ? 'First language' : 'Not first language')],
  ] as const) {
    const rows = summarizeBy(passenger, key);
    if (rows.length > 1) out.push(`## ${title}`, '', table(rows, ''), '');
  }

  const problems = takes.filter((t) => t.outcome === 'wrong' || t.outcome === 'missed' || t.outcome === 'silent').slice(-40).reverse();
  out.push('## What went wrong', '');
  if (!problems.length) out.push('Nothing: every take was right first time or after “Did you mean…?”.', '');
  else {
    out.push('Most recent first (up to 40). Use these to add words to the catalogue or to tune the matcher, then re-test with the lab.', '');
    out.push('| Language | Asked for | Whisper heard | Shown | Outcome |', '| --- | --- | --- | --- | --- |');
    for (const t of problems) {
      const shown = t.options.length ? `Did you mean: ${t.options.map((o) => labItemLabel(t.speaker, o)).join(', ')}` : labItemLabel(t.speaker, t.got);
      out.push(`| ${langLabel(t)} | ${cell(labItemLabel(t.speaker, t.expected))} | ${cell(t.transcript || '…')} | ${cell(t.outcome === 'silent' ? '—' : shown)} | ${OUTCOME_LABEL[t.outcome]} |`);
    }
    out.push('');
  }

  out.push(
    '## Read this with care',
    '',
    `- ${people.size} ${people.size === 1 ? 'person' : 'people'} is not a field trial. Teammates know the system and tend to speak clearly; real passengers will do worse.`,
    new Set(passenger.map((t) => t.mode)).size > 1
      ? '- Reading a given sentence is easier than asking in your own words: compare the two rows above.'
      : `- All passenger takes here were “${LAB_MODES[passenger[0]?.mode ?? 'read']}”. ${passenger[0]?.mode === 'own-words' ? '' : 'Reading a given sentence is easier than asking in your own words; the own-words task is the better estimate.'}`.trimEnd(),
    '- Place and microphone were reported by the speaker. “Cabin noise” was synthetic noise played in the room, not a real aircraft.',
    '- “Speech error rate” counts words (characters for Japanese and Thai) that Whisper got wrong against the sentence the person was asked to read, as total mistakes ÷ total words. It is only computed for read takes; own-words takes have no reference sentence.',
    '- Every take is kept in the log (except ones the speaker discarded as unfair, e.g. a cough or a misread).',
    '',
  );
  return out.join('\n');
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

function table(rows: LabSummary[], first: string): string {
  const head = [first, 'Takes', ...LAB_OUTCOMES.map((o) => OUTCOME_LABEL[o]), 'Had to tap or type', 'Speech error rate', 'Median on hub', '90% within', '95% within'];
  const lines = [`| ${head.join(' | ')} |`, `| ${head.map((_, i) => (i === 0 ? '---' : '---:')).join(' | ')} |`];
  for (const r of rows) {
    lines.push(
      `| ${[
        cell(r.label),
        String(r.takes),
        ...LAB_OUTCOMES.map((o) => `${pct(r.counts[o], r.takes)} (${r.counts[o]})`),
        `${Math.round(r.fallbackRate * 100)}%`,
        r.wer ? `${fmtRate(r.wer)} (${r.wer.unit === 'character' ? 'char' : 'word'}, ${r.werTakes})` : '—',
        fmtSeconds(r.medianMs),
        fmtSeconds(r.p90Ms),
        fmtSeconds(r.p95Ms),
      ].join(' | ')} |`,
    );
  }
  return lines.join('\n');
}
