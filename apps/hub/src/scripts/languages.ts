/**
 * Writes docs/languages.md: what each language really covers, and what the
 * matcher scores on sentences it was never tuned on.
 *
 *   npm run languages -w @hearme/hub
 *
 * Needs no models and no network: the numbers here come from the keyword
 * matcher alone, which runs anywhere. That makes this the floor beneath
 * HearMe's accuracy rather than its headline — the embedding model and the
 * trained classifier only go on top of it, and `npm run eval` measures those.
 * Reporting the floor separately means one table nobody can accuse of needing
 * a GPU to reproduce.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CORE_NEEDS,
  LANGUAGES,
  NEEDS,
  PASSENGER_PATH_KEYS,
  REPLIES,
  STRINGS,
  createKeywordMatcher,
  decide,
  describeCoverage,
  languageInfo,
  localePack,
  translatedKeys,
  type LangCode,
} from '@hearme/shared';
import { HELDOUT_PHRASES } from '@hearme/shared/lab';

const OUT = fileURLToPath(new URL('../../../../docs/languages.md', import.meta.url));

const withPacks = createKeywordMatcher();
const withoutPacks = createKeywordMatcher(CORE_NEEDS);

interface Scored {
  n: number;
  top1: number;
  inTop3: number;
  wrongButConfident: number;
}

function score(matcher: typeof withPacks, set: Record<string, string>): Scored {
  let top1 = 0;
  let inTop3 = 0;
  let wrongButConfident = 0;
  for (const [expected, sentence] of Object.entries(set)) {
    const d = decide(matcher.match(sentence));
    const options = d.kind === 'confident' ? [d.needId] : d.options;
    if (options[0] === expected) top1 += 1;
    if (options.includes(expected)) inTop3 += 1;
    if (d.kind === 'confident' && d.needId !== expected) wrongButConfident += 1;
  }
  return { n: Object.keys(set).length, top1, inTop3, wrongButConfident };
}

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : '—');
const totalStrings = Object.keys(STRINGS).length;

const out: string[] = [];
out.push('# Languages: what is actually covered', '');
out.push(
  `_Generated by \`npm run languages -w @hearme/hub\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`,
  '',
  'HearMe does not have a list of "supported languages". Speech recognition, understanding a request, the screens a passenger reads, the replies they get back and reading those replies aloud are five separate pieces of work, and a language can be finished in some and unfinished in others. This file says which, for each one.',
  '',
);

// ── Coverage matrix ───────────────────────────────────────────────────────
out.push('## Coverage, layer by layer', '');
out.push('| Language | | Speech in | Understands requests | Passenger screens | Crew replies | Read aloud | Wording checked by |');
out.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const l of LANGUAGES) {
  const c = l.coverage;
  const screens = c.ui === 'complete' ? 'all' : `${translatedKeys(l.code).length}/${totalStrings}, rest in ${languageInfo(l.fallback).englishName}`;
  out.push(
    `| **${l.nativeName}** | ${l.englishName}${l.core ? '' : ' (pack)'} | ${c.speech} | ${c.intent === 'complete' ? `all ${NEEDS.length} needs` : c.intent} | ${screens} | ${c.replies === 'complete' ? `all ${REPLIES.length}` : c.replies} | ${c.tts} | ${c.review} |`,
  );
}
out.push('');
out.push(
  `A "pack" language is one added as a data file (\`packages/shared/src/i18n/packs/<code>.ts\`) rather than written into every catalogue. It carries its own request vocabulary, its ${PASSENGER_PATH_KEYS.length}-string passenger path, all ${REPLIES.length} verified replies and all ${NEEDS.length} need labels, and falls back to a core language for the screens it has not translated — settings detail, the announcement list, and the safety briefing.`,
  '',
  '**Nothing here has been reviewed by a native speaker.** Every row says `non-native`, and that is the single biggest gap before a pilot. Care Mode wording and the safety briefing are deliberately *not* translated in any pack: they are the text a crew member acts on medically, so they need clinical and airline review in each language and until then they appear in the fallback language.',
  '',
);

// ── Where the words came from ─────────────────────────────────────────────
out.push('## Where each pack language’s words came from', '');
for (const l of LANGUAGES.filter((x) => !x.core)) {
  out.push(`- **${l.englishName}** (${l.nativeName}) — ${localePack(l.code)!.provenance}${l.note ? ` ${l.note}` : ''}`);
}
out.push('');

// ── Measured: keyword matcher alone ───────────────────────────────────────
out.push('## Measured: the keyword matcher alone, on held-out sentences', '');
out.push(
  'Twelve requests per language, one phrasing each, written after the vocabulary was fixed and never used to tune it. Scored by the keyword matcher **with no embedding model and no trained classifier** — so these numbers reproduce on any laptop with `npm run languages -w @hearme/hub`, and they are a floor, not the headline. `npm run eval -w @hearme/hub` measures the full pipeline.',
  '',
  '"Before" is the same sentences with the language packs switched off, which is what HearMe scored on these languages previously.',
  '',
);
out.push('| Language | | n | top-1 before | top-1 now | right picture offered before | right picture offered now | wrong but sent confidently |');
out.push('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |');
const totals = { n: 0, before1: 0, after1: 0, before3: 0, after3: 0, wrong: 0 };
for (const l of LANGUAGES) {
  const set = HELDOUT_PHRASES[l.code as LangCode];
  if (!set) continue;
  const before = score(withoutPacks, set);
  const after = score(withPacks, set);
  totals.n += after.n;
  totals.before1 += before.top1;
  totals.after1 += after.top1;
  totals.before3 += before.inTop3;
  totals.after3 += after.inTop3;
  totals.wrong += after.wrongButConfident;
  out.push(
    `| ${l.nativeName} | ${l.englishName}${l.core ? '' : ' (pack)'} | ${after.n} | ${pct(before.top1, before.n)} | ${pct(after.top1, after.n)} | ${pct(before.inTop3, before.n)} | ${pct(after.inTop3, after.n)} | ${after.wrongButConfident} |`,
  );
}
out.push(
  `| **All** | | **${totals.n}** | **${pct(totals.before1, totals.n)}** | **${pct(totals.after1, totals.n)}** | **${pct(totals.before3, totals.n)}** | **${pct(totals.after3, totals.n)}** | **${totals.wrong}** |`,
  '',
);
out.push(
  '- The six core languages are unchanged: the packs added vocabulary, they did not disturb what was already there.',
  '- Marathi starts higher than the other three without a pack because it is written in the same script as Hindi, so some Hindi keywords already matched it.',
  '- **The pack languages’ numbers are optimistic.** Their vocabulary and these test sentences were written by the same author, so words overlap in a way they would not for a sentence from a real passenger. The six core languages do not have this problem. A native speaker writing a fresh set is the fix, and it has not been done.',
  '- Two sentences still fail on keywords alone (Bengali and Punjabi, both "my body isn’t doing well", neither containing a catalogue word). They were left failing rather than adding those exact words, which would have tuned the vocabulary on the held-out set and made this whole table meaningless. Phrasings with no keyword are what the embedding model is for.',
  '',
);

// ── What is not measured ──────────────────────────────────────────────────
out.push('## What these numbers do not tell you', '');
out.push(
  '- **Nothing here involves a microphone.** These are typed sentences. Spoken accuracy needs Whisper, and is measured by `npm run eval -w @hearme/hub -- --speech` (synthetic voices) and the voice lab (real people).',
  '- **Punjabi and Marathi speech is unmeasured.** Whisper lists both, but macOS has no `say` voice for either, so the synthetic-speech evaluation skips them and reports that it did. They need real speakers in the voice lab.',
  '- **Bengali and Tamil speech is weak**, measured earlier at 42–50% of spoken requests right first time. Whisper-small hears these languages poorly; a larger speech model is the obvious next step.',
  '- **No native-speaker review, anywhere.** See the table above.',
  '',
);

// ── Per-language detail ───────────────────────────────────────────────────
out.push('## In plain words', '');
for (const l of LANGUAGES.filter((x) => !x.core)) {
  out.push(`### ${l.nativeName} — ${l.englishName}`, '');
  for (const row of describeCoverage(l.code)) out.push(`- **${row.layer}:** ${row.status}`);
  out.push('');
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out.join('\n'));
console.log(`Wrote ${OUT}`);
console.log(`\nKeyword matcher alone, ${totals.n} held-out sentences: top-1 ${pct(totals.before1, totals.n)} → ${pct(totals.after1, totals.n)}, right picture offered ${pct(totals.before3, totals.n)} → ${pct(totals.after3, totals.n)}, wrong-but-confident ${totals.wrong}.`);
